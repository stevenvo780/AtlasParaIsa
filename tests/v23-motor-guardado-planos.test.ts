import assert from 'node:assert/strict';
import test from 'node:test';
import { codigoForma } from '../src/shared/materia.js';
import { invent, inventionCandidates } from '../src/world/inventions.js';
import { reservaJ } from '../src/world/materia/cuerpo.js';
import { sustanciasDe } from '../src/world/materia/ley-mundo.js';
import { ServicioQuimicoImpl } from '../src/world/materia/servicio.js';
import { Rol } from '../src/world/materia/tipos.js';
import { ctxMateriaDe } from '../src/world/motor/acceso.js';
import { Buzones } from '../src/world/motor/buzon.js';
import { crearLibros } from '../src/world/motor/contadores.js';
import { Dueno } from '../src/world/motor/contexto.js';
import { RegistroContenido } from '../src/world/motor/registro.js';
import { addEvent, createWorld } from '../src/world/mundo/crear.js';
import { parseParams } from '../src/world/params.js';

test('dos dueños que ensayan la misma planta solo publican el primer plano', prueba => {
  const registro = new RegistroContenido(2);
  const remoto = new RegistroContenido(registro.memoria!);
  const params = parseParams({ v23: { materia: true, natalidad: true, cuerpos: true, tecnica: true, obra: true } });
  const forma = codigoForma({ largo: 1, ancho: 1, grueso: 0.12, hueco: 0.25, filo: 0 });
  const contextos = [registro, remoto].map((catalogo, i) => {
    const mundo = createWorld(7, params), persona = mundo.people[i]!;
    const tile = mundo.tiles.find(t => t.x % 16 === 8 && t.y % 16 === 8 && ['soil', 'meadow'].includes(t.terrain));
    assert.ok(tile);
    persona.x = tile.x; persona.y = tile.y; persona.target = { x: tile.x, y: tile.y };
    persona.fatigue = 0;
    persona.thirst = 0.8;
    persona.hunger = 0;
    mundo.tick = 10 + i;
    const buzones = new Buzones(1), azar = () => 0.5;
    const dueno = new Dueno(mundo, { hilo: 0, hilos: 1, buzones, buzon: buzones.dueno(0, azar),
      libros: crearLibros(1), contadores: null, registro: catalogo, azar, control: null, materia: null, enlace: null });
    dueno.abrirEpoca();
    const c = ctxMateriaDe(mundo);
    const { quimica } = c;
    assert.ok(quimica instanceof ServicioQuimicoImpl);
    prueba.after(() => quimica.cerrar());
    const lote = c.materia.nuevo(Rol.Objeto, -1, forma);
    c.materia.fuente(lote, Float64Array.of(sustanciasDe(c).SiO2, 500_000), c.libro);
    persona.carga = [lote];
    return { mundo, persona, c };
  });
  const [primero, segundo] = contextos;
  const propuestas = ({ mundo, persona }: typeof primero) => inventionCandidates(mundo, persona).map(c => c.planoMaterial);
  assert.equal(propuestas(primero).length, 1);
  assert.deepEqual(propuestas(primero), propuestas(segundo));
  const reservaPrimera = reservaJ(primero.c, primero.persona.cuerpo!);
  const reservaSegunda = reservaJ(segundo.c, segundo.persona.cuerpo!);
  assert.ok(invent(primero.mundo, primero.persona, e => addEvent(primero.mundo, e)));
  assert.ok(reservaJ(primero.c, primero.persona.cuerpo!) < reservaPrimera);
  assert.equal(invent(segundo.mundo, segundo.persona, e => addEvent(segundo.mundo, e)), false);
  assert.equal(reservaJ(segundo.c, segundo.persona.cuerpo!), reservaSegunda);
  assert.equal(primero.mundo.inventionDynamics.accepted, 1);
  assert.equal(segundo.mundo.inventionDynamics.accepted, 0);
  assert.equal(segundo.mundo.blueprints.length, 1);
  assert.equal(primero.mundo.blueprints.length, 2);
  const plano = primero.mundo.blueprints[1]!;
  assert.equal(plano.tick, primero.mundo.tick);
  assert.equal(plano.inventorId, primero.persona.id);
  assert.equal(plano.generation, 1);
  assert.deepEqual(plano.parents, ['blueprint-base']);

  const recargado = new RegistroContenido(2);
  recargado.cargar(registro.guardar());
  const id = Number(plano.id.slice('blueprint-obra-'.length));
  const firma = registro.leer(id)!;
  assert.deepEqual(recargado.leer(id), firma);
  assert.equal(recargado.insertarNuevo(firma, () => assert.fail('un plano guardado no vuelve a pagar la inscripción')), undefined);
});
