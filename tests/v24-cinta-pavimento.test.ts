import assert from 'node:assert/strict';
import test from 'node:test';
import { clientDelta, codificarBloque, decodificarBloque } from '../src/server/cinta/formato.js';
import { estadoVista, fotogramaAVista } from '../src/server/cinta/vista.js';
import { fotogramaDe, regionesRanura, RANURA_I32 } from '../src/shared/fotograma.js';
import { escalon } from '../src/shared/interruptores.js';
import { codigoForma } from '../src/shared/materia.js';
import { applyClientTapeDelta } from '../src/shared/tape-delta.js';
import { createWorld, tileAt } from '../src/world/index.js';
import { empedrar } from '../src/world/inventions.js';
import { sustanciasDe } from '../src/world/materia/ley-mundo.js';
import { calidadEmpedrado, celdaObra, lotesEnObra, trasladarLoteObra } from '../src/world/materia/piezas.js';
import { Rol } from '../src/world/materia/tipos.js';
import { ctxMateriaDe } from '../src/world/motor/acceso.js';
import { unSoloDueno, REF_NULA } from '../src/world/motor/contratos.js';
import { crearMotor } from '../src/world/motor/coordinador.js';
import { escribirFotograma } from '../src/world/motor/fotograma.js';
import { parseParams } from '../src/world/params.js';
import { PAGE_CELLS } from '../src/world/soa/region.js';

test('la cinta conserva una piedra material y su retirada en L0', async t => {
  const mundo = createWorld(42, parseParams({ v23: escalon('obra') }));
  Object.assign(mundo.people[2]!, { x: 16, y: 13 });
  const motor = crearMotor(mundo, unSoloDueno(42));
  t.after(() => motor.cerrar());
  motor.cargar({ world: mundo, materia: null }, 0);
  const c = ctxMateriaDe(mundo), tile = tileAt(mundo, { x: 16, y: 13 })!;
  tile.terrain = 'meadow';
  const forma = codigoForma({ largo: 1, ancho: 1, grueso: 0.2, hueco: 0, filo: 0 });
  const piedra = c.materia.nuevo(Rol.Objeto, REF_NULA, forma);
  c.materia.fuente(piedra, Float64Array.of(sustanciasDe(c).SiO2, 500_000, 0, 2_000_000), c.libro);
  const persona = mundo.people[2]!; persona.carga!.push(piedra);
  assert.ok(empedrar(c, persona, tile));
  assert.ok(calidadEmpedrado(c, tile) > 0);
  assert.equal(tile.paved, undefined);
  const estado = estadoVista(0);
  function corte(completo: boolean) {
    const capO = 0, capP = c.terreno.paginas;
    const ranura = new SharedArrayBuffer(regionesRanura(capO, capP).total);
    const i32 = new Int32Array(ranura, 0, 8);
    i32[RANURA_I32.completo] = Number(completo); i32[RANURA_I32.capOrganismos] = capO; i32[RANURA_I32.capPaginas] = capP;
    const f = { ranura, completo, tick: mundo.tick, epoca: 0, versiones: new Float64Array(capP) };
    assert.ok(escribirFotograma(c, f, []));
    const frame = fotogramaDe(ranura);
    const paginas = [];
    for (let i = 0; i < frame.paginas.length; i += 2) paginas.push({ tipo: 'pagina' as const, id: `${frame.paginas[i]},${frame.paginas[i + 1]}`, vista: Array.from({ length: PAGE_CELLS }, () => ({ terrain: 'meadow' as const, moisture: 0, vegetation: 0, food: 0 })) });
    return fotogramaAVista(estado, frame, completo ? [{ tipo: 'mundo', id: '', vista: { width: mundo.width, height: mundo.height } }, { tipo: 'clima', id: '', vista: mundo.weather }, ...paginas] : paginas, completo ? 1 : 2);
  }
  const base = corte(true).vista;
  assert.ok(base.tiles.find(p => p.x === tile.x && p.y === tile.y)?.paved! > 0);
  const celda = celdaObra(c, tile), [pieza] = lotesEnObra(c, celda, Rol.Pieza);
  trasladarLoteObra(c, pieza!, Rol.Objeto, celda, forma);
  c.propio.marcar(c.terreno.chunkDe(celda), true);
  assert.equal(calidadEmpedrado(c, tile), 0);
  const cambios = corte(false).tilesCambiadas;
  assert.ok(Array.isArray(cambios));
  const actual = { ...base, tick: base.tick + 1, tiles: cambios };
  const bloque = decodificarBloque(codificarBloque(0, base, [clientDelta(base, actual)]));
  assert.ok(bloque.baseFrame.tiles.find(p => p.x === tile.x && p.y === tile.y)?.paved! > 0);
  const recibido = applyClientTapeDelta(bloque.baseFrame, bloque.deltas[0]!).frame;
  assert.equal(recibido.tiles.find(p => p.x === tile.x && p.y === tile.y)?.paved, undefined);
});
